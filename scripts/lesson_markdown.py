#!/usr/bin/env python3
"""A small Markdown renderer for the lesson pages — standard library only.

Why this exists instead of `import markdown`
--------------------------------------------
The lesson pages are generated by `scripts/build_lesson_pages.py`, which runs in **six** workflows
(`docs.yml`, `update-lessons.yml`, `publish-dist.yml`, `intake-batch-convert.yml`, `pr-welcome.yml`,
plus the test suite). Each of those installs its own short list of packages — `lesson-gate.yml`
installs `pyyaml` and nothing else. A third-party renderer would mean editing six install steps and
rediscovering, one workflow at a time, the ones that were missed; that is the failure mode
`lessons/contrib/a-green-test-suite-hid-a-module-that-a-bare-node-runtime-cannot-load-*.md` describes,
one language over. It would also make the generated tree depend on the library's version, so a
`markdown` 3.12 could change 949 committed files that nobody edited.

So this file exists, and it renders exactly the constructs the corpus uses (measured 2026-11-16 over
988 lesson files): fenced code 75%, ordered lists 49%, `###` 34%, `*emphasis*` 25%, tables 20%,
`[links](…)` 8%, blockquotes 6%, nested bullets 5%, `####` 2%, indented code blocks (18 lines), one
image. Nothing else. What is not here is not rendered — no footnotes, no HTML passthrough, no
reference links — and that is a deliberate boundary rather than an unfinished one.

Escaping is the part worth reading twice
----------------------------------------
The corpus is *about* software, so its prose is full of things that look like markup: `<user>`,
`<path>`, `<n>`, `<decision-doc>` — 81 of the 988 files contain one outside a code block. A browser
would swallow `<user>` as an unknown HTML tag and the reader would see a hole. Every input character
is therefore escaped **first**, and only the tags this renderer emits exist in the output; `<user>`
reaches the page as visible text. Two consequences follow, both wanted:

* a lesson can never inject markup into the site — there is no passthrough to configure wrongly;
* a lesson that quotes HTML shows the HTML, which is what its author meant.

The one place raw HTML is *not* shown is `<!-- … -->` outside code, which markdown treats as an
invisible comment; it is dropped here for the same reason.

Usage:
    python3 scripts/lesson_markdown.py lessons/core/some-lesson.md    # print the rendered HTML
"""
from __future__ import annotations

import html as _html
import re
import sys
from pathlib import Path

#: Frontmatter is the gateway's, not the renderer's: `build_lesson_pages.py` strips it before calling
#: in, and this pattern is exported so both sides strip the same thing.
FRONTMATTER = re.compile(r"\A---\r?\n.*?\r?\n---[ \t]*\r?\n", re.S)

#: Code fences may be indented by up to three spaces (CommonMark), and closed by the same character
#: run they opened with. Both spellings occur in the corpus.
_FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})\s*([\w+#.-]*)")

_HEADING = re.compile(r"^ {0,3}(#{1,6})\s+(.*?)\s*#*\s*$")
_HR = re.compile(r"^ {0,3}(?:-{3,}|\*{3,}|_{3,})\s*$")
_BULLET = re.compile(r"^( *)([-*+])\s+(.*)$")
_ORDERED = re.compile(r"^( *)(\d{1,9})[.)]\s+(.*)$")
_COMMENT = re.compile(r"<!--.*?-->", re.S)


def _escape(text: str) -> str:
    return _html.escape(text, quote=False)


# ── inline ───────────────────────────────────────────────────────────────────────────────────────
# Ordered so that each pass cannot see what a later pass emits: code spans first (their contents must
# stay literal), then links and images, then emphasis. Every pattern runs on already-escaped text, so
# no `<` from the source survives as anything but `&lt;`.
_CODE_SPAN = re.compile(r"`([^`\n]+)`")
_IMAGE = re.compile(r"!\[([^\]]*)\]\(\s*([^)\s]+)\s*\)")
_LINK = re.compile(r"\[([^\]]+)\]\(\s*([^)\s]+)\s*\)")
_AUTOLINK = re.compile(r"&lt;(https?://[^\s&]+?)&gt;")
_BOLD = re.compile(r"\*\*(?=\S)(.+?)(?<=\S)\*\*")
_ITALIC = re.compile(r"(?<![\w*])\*(?=\S)([^*]+?)(?<=\S)\*(?![\w*])")

#: Link targets that are not a document on this site or the wider web. `javascript:` in a lesson is
#: far more likely to be quoted code than an instruction to a reader, and it must never become an
#: attribute — the same reason the renderer escapes rather than trusts.
_SAFE_TARGET = re.compile(r"^(?:https?://|mailto:|/|#|\.{1,2}/)")


def _link_target(raw: str) -> str | None:
    """The href for a markdown link, or None when the target is not one we will emit."""
    target = raw.strip()
    if not target or not _SAFE_TARGET.match(target):
        return None
    # `_escape` already turned `&` into `&amp;`, which is what an attribute needs; quotes cannot
    # reach here because the patterns stop at whitespace and `)`.
    return target


def inline(text: str) -> str:
    """Inline markdown (code, links, emphasis) for one already-escaped run of text."""

    def code(match: re.Match[str]) -> str:
        return f"<code>{match.group(1)}</code>"

    def image(match: re.Match[str]) -> str:
        alt, target = match.group(1), _link_target(_html.unescape(match.group(2)))
        if target is None:
            return match.group(0)
        # Rendered as a link rather than an <img>: the only image in the corpus is a badge example,
        # and a remote image on a generated page is a request this site does not need to make.
        return f'<a href="{_escape(target)}">{alt or _escape(target)}</a>'

    def link(match: re.Match[str]) -> str:
        target = _link_target(_html.unescape(match.group(2)))
        if target is None:
            return match.group(0)
        return f'<a href="{_escape(target)}">{match.group(1)}</a>'

    text = _CODE_SPAN.sub(code, text)
    text = _IMAGE.sub(image, text)
    text = _LINK.sub(link, text)
    text = _AUTOLINK.sub(lambda m: f'<a href="{m.group(1)}">{m.group(1)}</a>', text)
    text = _BOLD.sub(lambda m: f"<strong>{m.group(1)}</strong>", text)
    text = _ITALIC.sub(lambda m: f"<em>{m.group(1)}</em>", text)
    return text


# ── blocks ───────────────────────────────────────────────────────────────────────────────────────
def _is_blank(line: str) -> bool:
    return not line.strip()


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _starts_block(line: str) -> bool:
    """Does this line begin a block that a paragraph cannot swallow?"""
    stripped = line.strip()
    return bool(
        _FENCE.match(line)
        or _HEADING.match(line)
        or _HR.match(line)
        or _BULLET.match(line)
        or _ORDERED.match(line)
        or stripped.startswith(">")
        or _indent(line) >= 4
        or (stripped.startswith("|") and stripped.endswith("|"))
    )


def _fence(lines: list[str], start: int) -> tuple[str, int]:
    """A fenced code block. An unclosed fence runs to the end of the document, as CommonMark says."""
    opener = _FENCE.match(lines[start])
    assert opener is not None
    marker, language = opener.group(1)[0], opener.group(2)
    body: list[str] = []
    index = start + 1
    while index < len(lines):
        candidate = lines[index].strip()
        if candidate.startswith(marker * 3) and set(candidate.split(" ")[0]) <= {marker}:
            index += 1
            break
        body.append(lines[index])
        index += 1
    attribute = f' class="language-{_escape(language)}"' if language else ""
    return f"<pre><code{attribute}>{_escape(chr(10).join(body))}</code></pre>", index


def _table(lines: list[str], start: int) -> tuple[str, int] | None:
    """A pipe table, when the line after the header is a separator row."""
    header = lines[start].strip()
    if start + 1 >= len(lines):
        return None
    rule = lines[start + 1].strip()
    if not re.fullmatch(r"\|?[\s:|-]+\|?", rule) or "-" not in rule:
        return None

    def cells(row: str) -> list[str]:
        row = row.strip()
        if row.startswith("|"):
            row = row[1:]
        if row.endswith("|"):
            row = row[:-1]
        return [cell.strip() for cell in row.split("|")]

    head = "".join(f"<th>{inline(_escape(cell))}</th>" for cell in cells(header))
    rows: list[str] = []
    index = start + 2
    while index < len(lines) and lines[index].strip().startswith("|"):
        body = "".join(f"<td>{inline(_escape(cell))}</td>" for cell in cells(lines[index]))
        rows.append(f"<tr>{body}</tr>")
        index += 1
    body_html = f"<tbody>{''.join(rows)}</tbody>" if rows else ""
    return f"<table><thead><tr>{head}</tr></thead>{body_html}</table>", index


def _list(lines: list[str], start: int) -> tuple[str, int]:
    """A bullet or ordered list, nested by indentation, one level at a time and recursively."""
    first = _BULLET.match(lines[start]) or _ORDERED.match(lines[start])
    assert first is not None
    ordered = bool(_ORDERED.match(lines[start]))
    base_indent = len(first.group(1))
    pattern = _ORDERED if ordered else _BULLET
    items: list[tuple[list[str], list[str]]] = []  # (own text lines, nested lines)
    index = start
    while index < len(lines):
        line = lines[index]
        if _is_blank(line):
            # A blank line ends the list unless the next non-blank line is still part of it.
            lookahead = index + 1
            while lookahead < len(lines) and _is_blank(lines[lookahead]):
                lookahead += 1
            if lookahead >= len(lines) or not pattern.match(lines[lookahead]) \
                    or len(pattern.match(lines[lookahead]).group(1)) < base_indent:  # type: ignore[union-attr]
                break
            index = lookahead
            continue
        match = pattern.match(line)
        if match and len(match.group(1)) <= base_indent:
            items.append(([match.group(3)], []))
            index += 1
            continue
        if match and len(match.group(1)) > base_indent:
            if not items:
                break
            items[-1][1].append(line)
            index += 1
            continue
        if _indent(line) > base_indent and items:
            items[-1][1].append(line)
            index += 1
            continue
        break

    tag = "ol" if ordered else "ul"
    rendered: list[str] = []
    for own, nested in items:
        text = " ".join(part.strip() for part in own)
        if not nested:
            rendered.append(f"<li>{inline(_escape(text))}</li>")
            continue
        # A continuation of the same sentence is prose; anything that starts a block is content. The
        # distinction matters: rendering an indented wrap of one sentence as its own <p> splits a
        # bullet into two paragraphs, which is how 500 list items in the first draft of this renderer
        # came out looking broken.
        depth = min((_indent(line) for line in nested if line.strip()), default=0)
        dedented = [line[depth:] if line.strip() else "" for line in nested]
        if any(_starts_block(line) for line in dedented if line.strip()):
            inner = render("\n".join(dedented))
            rendered.append(f"<li>{inline(_escape(text))}{inner}</li>")
        else:
            joined = " ".join(line.strip() for line in dedented if line.strip())
            rendered.append(f"<li>{inline(_escape(f'{text} {joined}'))}</li>")
    return f"<{tag}>{''.join(rendered)}</{tag}>", index


def _blockquote(lines: list[str], start: int) -> tuple[str, int]:
    body: list[str] = []
    index = start
    while index < len(lines):
        stripped = lines[index].strip()
        if not stripped.startswith(">"):
            if _is_blank(lines[index]):
                break
            body.append(lines[index])
        else:
            body.append(stripped[1:].lstrip())
        index += 1
    inner, _ = _blocks(body)
    return f"<blockquote>{inner}</blockquote>", index


def _indented_code(lines: list[str], start: int) -> tuple[str, int]:
    body: list[str] = []
    index = start
    while index < len(lines):
        line = lines[index]
        if _is_blank(line):
            body.append("")
            index += 1
            continue
        if _indent(line) < 4 and not line.startswith("\t"):
            break
        body.append(line[4:] if line.startswith("    ") else line.lstrip("\t"))
        index += 1
    while body and body[-1] == "":
        body.pop()
    return f"<pre><code>{_escape(chr(10).join(body))}</code></pre>", index


def _blocks(lines: list[str]) -> tuple[str, int]:
    """Render a run of lines as blocks. Returns the HTML and the index it stopped at."""
    out: list[str] = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if _is_blank(line):
            index += 1
            continue

        if _FENCE.match(line):
            html, index = _fence(lines, index)
            out.append(html)
            continue

        heading = _HEADING.match(line)
        if heading:
            # A level-1 heading inside the body is demoted: the page already carries the lesson title
            # as its <h1>, and two of them is a structure a crawler has to guess at.
            level = max(2, len(heading.group(1)))
            out.append(f"<h{level}>{inline(_escape(heading.group(2)))}</h{level}>")
            index += 1
            continue

        if _HR.match(line):
            out.append("<hr>")
            index += 1
            continue

        if line.strip().startswith("|"):
            table = _table(lines, index)
            if table:
                html, index = table
                out.append(html)
                continue

        if line.strip().startswith(">"):
            html, index = _blockquote(lines, index)
            out.append(html)
            continue

        if _BULLET.match(line) or _ORDERED.match(line):
            html, index = _list(lines, index)
            out.append(html)
            continue

        if _indent(line) >= 4 or line.startswith("\t"):
            html, index = _indented_code(lines, index)
            out.append(html)
            continue

        # Paragraph: everything up to the next blank line or the next block start.
        paragraph: list[str] = [line.strip()]
        index += 1
        while index < len(lines) and not _is_blank(lines[index]) and not _starts_block(lines[index]):
            paragraph.append(lines[index].strip())
            index += 1
        out.append(f"<p>{inline(_escape(' '.join(paragraph)))}</p>")
    return "".join(out), index


def render(markdown_text: str) -> str:
    """Render a lesson body to HTML. Frontmatter is stripped first, if it is still attached."""
    text = FRONTMATTER.sub("", markdown_text.replace("\r\n", "\n").replace("\r", "\n"))
    text = _COMMENT.sub("", text)
    html, _ = _blocks(text.split("\n"))
    return html


def main(argv: list[str] | None = None) -> int:
    arguments = sys.argv[1:] if argv is None else argv
    if len(arguments) != 1:
        print("usage: lesson_markdown.py <lesson.md>", file=sys.stderr)
        return 2
    path = Path(arguments[0])
    print(render(path.read_text(encoding="utf-8")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
