#!/usr/bin/env python3
"""Build `data/public-vocabulary.json` — the words the public corpus has ever used.

Why this file exists
--------------------
`scripts/lesson_gate.py` needs to answer one question about a submission: **is this command name
something the public corpus has ever seen?** That question cannot be answered by asking the author.
Measured 2026-10-28 on intake #3983: an agent described its employer's internal platform and its
private CLI (`mico issue rerun`, `mico wiki search`) without a single credential, so twelve redaction
rules passed it through, and the agent had no reference for what "internal" even meant. The word
looked ordinary to the writer.

The same check runs at intake (`workers/register-proxy-sw.js` → `unknownCommandSurface`, advisory
banner) but the worker asks its **own** BM25 index, which lives in KV and is built from full lesson
text. A lesson gate cannot reach that, so the corpus is exported here as a flat list. Two consumers,
one corpus, two derived vocabularies — they are allowed to differ in the *safe* direction (this file
is a subset of the index, so the gate errs toward flagging, never toward silence).

Two lists, and the split is the point
-------------------------------------
* ``corpus`` — regenerated every run from `data/lessons.json`. Never edit by hand; a `--check` run
  in CI fails when it drifts.
* ``allowlist`` — **human-asserted public tools the corpus has not used yet**. This is the escape
  hatch, and making it a visible diff is the whole design: an author who writes a lesson about a new
  public CLI adds one line saying "this is public", and a reviewer sees the claim. A silent pass
  would have been cheaper and would have taught nobody anything.

An internal tool does not belong in either list — it belongs rewritten, or declared with
`public_analogue:` in the lesson frontmatter, which is the gate's other accepted answer.

Usage
-----
    python3 scripts/export_public_vocabulary.py            # rewrite corpus
    python3 scripts/export_public_vocabulary.py --check    # fail if out of date (CI)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LESSONS = REPO / "data" / "lessons.json"
TARGET = REPO / "data" / "public-vocabulary.json"

# Same shape the worker's extractor accepts (`COMMAND_TOKEN`): a command head is a lowercase word,
# optionally dotted/dashed, 2-40 characters. Keeping the character class identical is what makes a
# token in this file mean the same thing on both sides.
TOKEN = re.compile(r"[a-z][a-z0-9._+-]{1,39}")

# Fields that carry prose. `preview` is a body excerpt; the full bodies live in `lessons/**`, which
# this script deliberately does not read — the gate runs on PRs that touch one file, and walking the
# corpus would make `--check` depend on the whole tree. Documented rather than discovered: the cost
# is that a word used only deep inside an old lesson body is "unknown" here, i.e. a false positive,
# which the allowlist or `public_analogue` resolves in one line.
PROSE_FIELDS = ("id", "title", "problem", "summary", "preview", "domain", "tags", "path",
                "summary_plain", "trigger", "triggers", "verify")


def corpus_tokens(rows: list[dict]) -> list[str]:
    """Every word the public corpus has used — metadata **and** lesson bodies.

    Bodies matter: built from `data/lessons.json` alone the vocabulary missed ordinary public tools
    that only appear inside a lesson's text (`unzip`, `copy-item`, `new-item`), and the gate flagged
    **47 lessons (7.2%)** for writing about public software. With the bodies included that number is
    zero *on the corpus as it stands* — which is the right shape, because the check is only ever
    allowed to have teeth on what is being **added**, not on what is already published.
    """
    tokens: set[str] = set()
    for row in rows:
        blob = " ".join(str(row.get(field) or "") for field in PROSE_FIELDS)
        tokens.update(TOKEN.findall(blob.lower()))
    for path in sorted((REPO / "lessons").rglob("*.md")):
        try:
            tokens.update(TOKEN.findall(path.read_text(encoding="utf-8", errors="ignore").lower()))
        except OSError:
            continue
    return sorted(tokens)


def load_existing() -> dict:
    if not TARGET.exists():
        return {}
    try:
        return json.loads(TARGET.read_text(encoding="utf-8"))
    except Exception:                                   # noqa: BLE001 — a broken file is rebuilt
        return {}


def build() -> dict:
    rows = json.loads(LESSONS.read_text(encoding="utf-8"))
    existing = load_existing()
    return {
        "_comment": [
            "Generated by scripts/export_public_vocabulary.py — do not edit `corpus` by hand.",
            "`allowlist` IS hand-edited: add a public tool name the corpus has not used yet, and the",
            "lesson gate stops flagging it. Adding an internal name here is the failure this file",
            "exists to prevent — write the lesson generically instead.",
        ],
        "generated_from": "data/lessons.json + lessons/**/*.md",
        "corpus_rows": len(rows),
        "corpus": corpus_tokens(rows),
        "allowlist": sorted(set(existing.get("allowlist") or [])),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 when the corpus list is out of date (CI mode)")
    args = ap.parse_args(argv)

    fresh = build()
    if args.check:
        current = load_existing()
        if not current:
            print("data/public-vocabulary.json is missing — run the exporter", file=sys.stderr)
            return 1
        if current.get("corpus") != fresh["corpus"]:
            old, new = set(current.get("corpus") or []), set(fresh["corpus"])
            print("data/public-vocabulary.json is out of date — run "
                  "`python3 scripts/export_public_vocabulary.py`", file=sys.stderr)
            if new - old:
                print(f"  missing: {', '.join(sorted(new - old)[:12])}", file=sys.stderr)
            if old - new:
                print(f"  stale:   {', '.join(sorted(old - new)[:12])}", file=sys.stderr)
            return 1
        print(f"up to date: {len(fresh['corpus'])} corpus tokens, "
              f"{len(current.get('allowlist') or [])} allowlisted")
        return 0

    TARGET.write_text(json.dumps(fresh, ensure_ascii=False, indent=0) + "\n", encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)}: {len(fresh['corpus'])} corpus tokens, "
          f"{len(fresh['allowlist'])} allowlisted")
    return 0


if __name__ == "__main__":
    sys.exit(main())
