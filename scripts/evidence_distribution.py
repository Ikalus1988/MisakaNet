#!/usr/bin/env python3
"""Count the corpus's evidence levels and print the distribution.

`docs/trust-semantics.md` defines E0-E4 and says a missing `evidence_level` reads
as E0. That rule makes a fact unanswerable from the documentation alone: **how many
lessons actually declare a level, and how many rely on the default?** A page of
prose cannot answer it, and a number pasted into prose goes stale the next time a
lesson lands — which is what happened to `docs/maintainer/growth-funnel.md`, whose
baseline has never been refreshed.

This script is the regenerable form of that number. `backlog-and-growth-2026-09-20.md`
§3.9 asked for the distribution to be published before any talk of a downgrade
mechanism; this is the publishable part.

Usage:
    python3 scripts/evidence_distribution.py              # human-readable table
    python3 scripts/evidence_distribution.py --json       # machine-readable
    python3 scripts/evidence_distribution.py --check FILE # exit 1 if FILE is stale

`--check` is what a CI step or a pre-commit hook should use: it fails when the
committed table no longer matches the corpus, so the number cannot rot silently the
way a hand-written one does.
"""
from __future__ import annotations

import argparse
import collections
import json
import pathlib
import re
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from misakanet.lesson_index import canonical_lessons  # noqa: E402

LEVELS = ("E0", "E1", "E2", "E3", "E4")
_FRONTMATTER = re.compile(r"^---\s*\n(.*?)\n---", re.S)
_EVIDENCE = re.compile(r"^\s*evidence_level:\s*\"?(E[0-4])\"?\s*$", re.M | re.I)
# `provenance.evidence` is the other accepted spelling (lesson_gate.py accepts either),
# so counting it separately would understate the declared levels.
_PROVENANCE_EVIDENCE = re.compile(r"^\s*evidence:\s*\"?(E[0-4])\"?\s*$", re.M | re.I)


def read_level(text: str) -> str | None:
    """The declared level, or None when the lesson relies on the E0 default."""
    m = _FRONTMATTER.match(text)
    if not m:
        return None
    body = m.group(1)
    hit = _EVIDENCE.search(body) or _PROVENANCE_EVIDENCE.search(body)
    return hit.group(1).upper() if hit else None


def collect(lessons_root: pathlib.Path | None = None) -> collections.Counter:
    """Counts keyed by E0-E4 plus `E0 (default)` for lessons that declare nothing."""
    counts: collections.Counter = collections.Counter()
    for path in canonical_lessons(lessons_root or REPO_ROOT / "lessons"):
        if path.name.upper() == "README.MD" or "TEMPLATE" in path.name.upper():
            continue
        level = read_level(path.read_text(encoding="utf-8", errors="replace"))
        counts[level or "E0 (default)"] += 1
    return counts


def render(counts: collections.Counter) -> str:
    total = sum(counts.values())
    rows = []
    rows.append(f"<!-- Generated by: python3 scripts/evidence_distribution.py -->")
    rows.append("")
    rows.append("| Level | Lessons | Share |")
    rows.append("|---|---|---|")
    for level in LEVELS:
        n = counts.get(level, 0)
        declared = level != "E0"
        rows.append(f"| **{level}**{' (declared)' if declared else ''} | {n} | "
                    f"{n / total * 100:.1f}% |" if total else f"| {level} | 0 | — |")
    default = counts.get("E0 (default)", 0)
    e0_total = counts.get("E0", 0) + default
    rows.append("")
    rows.append(f"- Total lessons: **{total}**")
    rows.append(f"- At **E0** in total (declared + default): **{e0_total}** "
                f"({e0_total / total * 100:.1f}%) — of which **{default}** declare no level at all")
    rows.append(f"- At **E4** (*observed reuse by two or more distinct clients*): "
                f"**{counts.get('E4', 0)}**")
    return "\n".join(rows)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--json", action="store_true", help="machine-readable output")
    ap.add_argument("--check", metavar="FILE",
                    help="exit 1 when FILE does not contain the current table")
    args = ap.parse_args()

    counts = collect()
    table = render(counts)

    if args.check:
        target = pathlib.Path(args.check)
        if not target.exists():
            print(f"missing: {target}", file=sys.stderr)
            return 1
        if table.strip() not in target.read_text(encoding="utf-8"):
            print(f"stale: {target} no longer matches the corpus — "
                  f"re-run `python3 scripts/evidence_distribution.py` and paste", file=sys.stderr)
            return 1
        print(f"ok: {target} matches the corpus")
        return 0

    if args.json:
        print(json.dumps(dict(sorted(counts.items())), ensure_ascii=False, indent=2))
    else:
        print(table)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
