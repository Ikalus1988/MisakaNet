#!/usr/bin/env python3
"""Rebuild a lesson pull request on today's `main`, so its conflicts are regenerated, not resolved.

Why this exists
---------------
A lesson pull request carries two kinds of change and they want opposite treatment:

* **the lesson files** — the deliverable, authored by a contributor, never to be regenerated;
* **every generated artifact** — `data/lessons.json`, `data/okf/lessons.jsonl`,
  `data/public-vocabulary.json`, `docs/data/*.json`, the generated site, `lessons/index.md`, … —
  produced by scripts, owned by nobody, and impossible to merge by hand.

Merging any lesson PR moves those artifacts, so every other lesson PR goes `DIRTY` on files it should
never have had to touch. Measured 2026-11-15: five rebuilds in one session, each the same eight steps
(`docs/maintainer/external-pr-triage.md` §3 names this the **adopt** verdict). Resolving the conflict
by hand is the one thing that must not happen: a half-merged `lessons.json` is a corpus nobody can
diff, and the generator would overwrite the resolution on the next run anyway.

What it does
------------
    python3 scripts/rebuild_lesson_pr.py 4982            # dry run: says what it would do
    python3 scripts/rebuild_lesson_pr.py 4982 --commit    # builds the branch and commits
    python3 scripts/rebuild_lesson_pr.py 4982 --push      # …and force-pushes the PR's head branch

1. refuses on a dirty worktree, and on any untracked `.md` under `lessons/` (the corpus exporter
   walks the disk, not git — an untracked file skews every count it produces);
2. fetches the PR head and splits its file list into **lesson** / **generated** / **other**;
   `other` is a refusal, because a rebuild can only reproduce the artifacts it knows how to run;
3. resets a scratch branch to `origin/main`, takes only the lesson files from the PR head;
4. runs the generator chain from `docs/agents/repo-operations.md`, then refreshes the evidence table
   that `scripts/evidence_distribution.py --check` guards;
5. verifies what came out — corpus size, the evidence check, `lesson_gate.py` per lesson — and stops
   if a lesson stopped being indexed (that is the silent failure an unterminated YAML quote causes);
6. commits with the original message plus `Signed-off-by` (you) and `Co-authored-by` (the author).

`--push` is opt-in. The repository's rule is that a maintainer decides what lands; this script makes
the decision cheap to execute, not automatic.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))

# The published paths are the repository's own answer to "which files does a generator own", held in
# one place by the publisher's assertion. A second list here would drift from it.
from ci.check_dist_diff import PUBLISHED  # noqa: E402

# The order is the one `docs/agents/repo-operations.md` prints; `gen_ranking_snapshot.py` is last
# because it reads `data/lessons.json`.
GENERATORS = (
    "update_lessons_json.py",
    "build_lesson_pages.py",
    "sync_lesson_count.py",
    "export_okf.py",
    "rebuild_lessons_index.py",
    "export_public_vocabulary.py",
    "gen_ranking_snapshot.py",
)

EVIDENCE_MARKER = "<!-- Generated by: python3 scripts/evidence_distribution.py -->"


# `PUBLISHED` answers "which artifacts must travel with the site". The chain this script runs writes
# two more files that are generated but not published, and both have to be reproducible here or the
# rebuilt branch is red for a reason nobody can fix by hand: the vocabulary export, and the evidence
# table that lives inside a hand-written document.
ALSO_GENERATED = (
    "data/public-vocabulary.json",
    "docs/trust-semantics.md",
    # `docs/data/` is written by workflows other than this chain (`build-feed.yml` produces the feed
    # and the activity series). A rebuild does not reproduce them — it leaves `main`'s copies alone —
    # but they are still not the pull request's own change, and treating them as `other` refused a
    # legitimate lesson pull request that had branched before the last feed refresh (measured: #4982).
    "docs/data/",
)


def is_generated(path: str) -> bool:
    """`PUBLISHED` entries are prefixes and globs; match the way the publisher does."""
    from ci.check_dist_diff import _matches  # noqa: PLC0415 — reuse the publisher's matcher

    return _matches(path, PUBLISHED) or path.startswith(ALSO_GENERATED)


def platform_refusal(os_name: str) -> str | None:
    """Why the generator chain must not run on Windows, or `None` when it may.

    Two independent measurements, both from running this chain on the Windows checkout:

    * **2026-11-15, non-ASCII filenames**: the same four generators produced **778** lessons instead of
      940 — every lesson whose filename is not ASCII dropped out with no error, only a smaller corpus.
      Under WSL the same run gives the correct count.
    * **2026-11-15, line endings**: writing the artifacts from Windows rewrote 21 tracked files with
      CRLF, which `tests/test_tracked_text_files_are_lf.py` refuses. The diff read
      `102549 insertions(+), 102549 deletions(-)` — the same content, every line changed.

    A rebuild script that quietly produces either of those is worse than no script, so the check is a
    refusal with an escape hatch rather than a warning.
    """
    if os_name == "nt":
        return ("refusing: the generator chain must run on POSIX. On Windows it drops lessons whose "
                "filenames are not ASCII (measured: 940 → 778 with no error) and rewrites the "
                "artifacts with CRLF. Run this under WSL, or pass --allow-windows if you have "
                "checked the corpus size and `git diff --stat` yourself.")
    return None


def classify(paths: list[str]) -> dict[str, list[str]]:
    """Split a pull request's file list into the three things a rebuild can be asked about."""
    lessons, generated, other = [], [], []
    for path in paths:
        if is_generated(path):
            generated.append(path)
        elif path.startswith("lessons/") and path.endswith(".md"):
            lessons.append(path)
        else:
            other.append(path)
    return {"lessons": sorted(lessons), "generated": sorted(generated), "other": sorted(other)}


def patch_evidence_table(doc: str, fresh: str) -> str:
    """Replace the generated block in `docs/trust-semantics.md` with `fresh`.

    The table is checked rather than trusted (`--check`), so adding a lesson makes it stale by
    definition and the check fails on the rebuilt branch. It is a generated block inside a hand-written
    document, which is why the replacement is bounded by its marker and its last line rather than by a
    heading search.
    """
    start = doc.find(EVIDENCE_MARKER)
    if start < 0:
        raise ValueError(f"{EVIDENCE_MARKER!r} not found — the document changed shape")
    end = doc.find("\n", doc.find("- At **E4**", start))
    if end < 0:
        raise ValueError("the evidence block no longer ends with its E4 line")
    return doc[:start] + EVIDENCE_MARKER + "\n\n" + fresh.strip() + "\n" + doc[end + 1:]


def commit_message(original: str, author: str) -> str:
    """The contributor's message, with the two trailers the DCO check and the credit need."""
    body = original.rstrip()
    # Drop trailers the original already carries: they belong to the author's commit, not this one.
    lines = [line for line in body.splitlines()
             if not line.startswith(("Signed-off-by:", "Co-authored-by:"))]
    body = "\n".join(lines).rstrip()
    if "<" not in author:  # `login <email>` when the caller knows the email
        author = f"{author} <{author}@users.noreply.github.com>"
    return f"{body}\n\nCo-authored-by: {author}"


def _env() -> dict[str, str]:
    """The environment every child gets: `GITHUB_TOKEN` removed.

    On this machine a stale `GITHUB_TOKEN` is injected by the host process and overrides the working
    credential in `gh`'s keyring, so `gh` answers `HTTP 401: Bad credentials` while `gh auth status`
    reports a healthy account. `gh` reads `GH_TOKEN`/`GITHUB_TOKEN` before the keyring, so the only
    fix at this level is to not pass it on.
    """
    env = dict(os.environ)
    for name in ("GITHUB_TOKEN", "GH_TOKEN"):
        env.pop(name, None)
    return env


def run(command: list[str], *, check: bool = True, quiet: bool = False) -> str:
    result = subprocess.run(command, cwd=REPO, capture_output=True, text=True, encoding="utf-8",
                            env=_env())
    if check and result.returncode != 0:
        raise SystemExit(f"failed: {' '.join(command)}\n{(result.stderr or result.stdout).strip()}")
    if not quiet and result.stdout.strip():
        print(result.stdout.strip())
    return result.stdout


def untracked_lessons() -> list[str]:
    out = run(["git", "-c", "core.quotePath=false", "ls-files", "--others", "--exclude-standard",
               "lessons"], check=False, quiet=True)
    return [line for line in out.splitlines() if line.strip().endswith(".md")]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("pr", type=int)
    parser.add_argument("--commit", action="store_true", help="build the branch and commit it")
    parser.add_argument("--push", action="store_true", help="also force-push the PR's head branch")
    parser.add_argument("--branch", default=None, help="scratch branch name (default: rebuild-<pr>)")
    parser.add_argument("--allow-windows", action="store_true",
                        help="run the generator chain on Windows anyway (see platform_refusal)")
    args = parser.parse_args(argv)

    refusal = platform_refusal(os.name)
    if refusal and not args.allow_windows:
        raise SystemExit(refusal)

    # Untracked files are ignored here on purpose: the ones that matter — a lesson the generator reads
    # off the disk — are checked by name on the next line, and an untracked script or scratch note is
    # not a reason to refuse a rebuild.
    dirty = [line for line in run(["git", "status", "--porcelain"], quiet=True).splitlines()
             if line.strip() and not line.startswith("??")]
    if dirty:
        raise SystemExit("refusing on a dirty worktree — commit, stash, or discard first:\n"
                         + "\n".join(dirty))
    stray = untracked_lessons()
    if stray:
        raise SystemExit("refusing: untracked lesson files skew every generator count — "
                         "move them out of `lessons/` first:\n  " + "\n  ".join(stray))

    meta = json.loads(run(["gh", "pr", "view", str(args.pr), "--json",
                           "headRefOid,headRefName,state,author,title"], quiet=True))
    if meta["state"] != "OPEN":
        raise SystemExit(f"#{args.pr} is {meta['state']}, nothing to rebuild")
    head, branch = meta["headRefOid"], meta["headRefName"]
    author = meta["author"]["login"]
    run(["git", "fetch", "origin", head], quiet=True)
    run(["git", "fetch", "origin", "main"], quiet=True)
    run(["git", "merge-base", "--is-ancestor", "origin/main", head], check=False, quiet=True)

    # Three-dot semantics, via an explicit merge base. `git diff origin/main head` also reports files
    # that `main` gained after the pull request branched, as if the pull request had changed them —
    # measured on #4982, where that made the script refuse a lesson pull request because `main` had
    # since gained a script of its own.
    base = run(["git", "merge-base", "origin/main", head], quiet=True).strip()
    paths = run(["git", "-c", "core.quotePath=false", "diff", "--name-only",
                 base, head], quiet=True).split("\n")
    groups = classify([p for p in paths if p.strip()])
    print(f"#{args.pr} {meta['title'][:70]}")
    for name, items in groups.items():
        print(f"  {name:9} {len(items)}")
        for item in items[:6]:
            print(f"            {item}")
        if len(items) > 6:
            print(f"            … {len(items) - 6} more")
    if groups["other"]:
        raise SystemExit("refusing: this is not a lesson-only pull request — a rebuild can only "
                         "reproduce the generated artifacts, and these are neither lesson nor "
                         "generated:\n  " + "\n  ".join(groups["other"]))
    if not groups["lessons"]:
        raise SystemExit("nothing to take: no lesson files in the diff")
    if not args.commit:
        print("\ndry run — pass --commit to build the branch, --push to update the pull request.")
        return 0

    scratch = args.branch or f"rebuild-{args.pr}"
    run(["git", "checkout", "-q", "-B", scratch, "origin/main"])
    run(["git", "-c", "core.quotePath=false", "checkout", head, "--", *groups["lessons"]])

    for script in GENERATORS:
        run([sys.executable, str(REPO / "scripts" / script)], quiet=True)
        print(f"  ran {script}")

    fresh = run([sys.executable, str(REPO / "scripts" / "evidence_distribution.py")], quiet=True)
    doc = REPO / "docs" / "trust-semantics.md"
    doc.write_text(patch_evidence_table(doc.read_text(encoding="utf-8"), fresh), encoding="utf-8")
    run([sys.executable, str(REPO / "scripts" / "evidence_distribution.py"),
         "--check", str(doc)], quiet=True)
    print("  evidence table refreshed")

    lessons = json.loads((REPO / "data" / "lessons.json").read_text(encoding="utf-8"))
    indexed = {entry.get("id") for entry in lessons}
    dropped = [p for p in groups["lessons"] if Path(p).stem not in indexed]
    if dropped:
        # The failure this catches: an unterminated quote in the frontmatter makes the whole block
        # unparseable, and `update_lessons_json.py` then omits the lesson with no error at all.
        raise SystemExit("refusing to commit: these lessons are not in the index — that is what a "
                         "frontmatter the generator could not parse looks like:\n  "
                         + "\n  ".join(dropped))
    print(f"  corpus: {len(lessons)} lessons")
    for path in groups["lessons"]:
        result = subprocess.run([sys.executable, str(REPO / "scripts" / "lesson_gate.py"), path],
                                cwd=REPO, capture_output=True, text=True, encoding="utf-8")
        if result.returncode != 0:
            findings = [line.strip() for line in (result.stdout or "").splitlines()
                        if line.strip().startswith("-")]
            print(f"  gate advisory: {Path(path).name} — {findings[:1]}")

    run(["git", "add", "-A", "data", "docs", "lessons", "tests/fixtures"])
    note = (f"Rebuilt on `origin/main` by `scripts/rebuild_lesson_pr.py` from #{args.pr} ({head[:9]}): "
            "only the lesson files were taken, every generated artifact was produced here.")
    # The note goes **before** the trailer block. Git only reads trailers from the last paragraph, so
    # appending it with a second `-m` moved `Co-authored-by` out of the block and it disappeared from
    # the commit — measured on #4982, where the credit was silently dropped.
    message = commit_message(meta["title"], author).replace(
        "Co-authored-by: ", f"{note}\n\nCo-authored-by: ", 1)
    run(["git", "commit", "-q", "-s", "-m", message])
    print(f"committed on {scratch}")
    if args.push:
        run(["git", "push", "--force-with-lease", "origin", f"{scratch}:{branch}"])
        print(f"pushed → {branch}")
    else:
        print(f"not pushed. Next:\n  git push --force-with-lease origin {scratch}:{branch}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
