#!/usr/bin/env python3
"""`scripts/rebuild_lesson_pr.py` — the eight steps a lesson-PR rebuild is made of, as three functions.

Why a rebuild exists at all: every lesson pull request touches the generated artifacts, so merging one
makes the others conflict on files no contributor should have had to touch. Measured 2026-11-15: five
rebuilds in one session, each the same eight commands. The parts that can be wrong without anyone
noticing are the *classification* (what is a lesson, what is a generator's, what is neither) and the
two text transforms (the evidence table, the commit trailers), so those are what this file pins.
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))

import rebuild_lesson_pr as rebuild  # noqa: E402


def test_a_lesson_diff_is_split_into_three_kinds():
    groups = rebuild.classify([
        "lessons/contrib/some-lesson.md",
        "data/lessons.json",
        "docs/data/lessons-lite.json",
        "lessons/index.md",
    ])
    assert groups["lessons"] == ["lessons/contrib/some-lesson.md"]
    assert "data/lessons.json" in groups["generated"]
    assert "lessons/index.md" in groups["generated"], (
        "lessons/index.md is generated — treating it as a lesson would mean never regenerating it")
    assert groups["other"] == []


def test_a_pull_request_that_touches_code_or_ci_is_refused_not_rebuilt():
    """A rebuild can only reproduce what the generator chain writes.

    Anything else — a script, a workflow, a test — is a review, not a rebuild, and rebuilding it would
    silently drop the change. That is why `other` is a refusal and not a warning.
    """
    groups = rebuild.classify(["scripts/foo.py", ".github/workflows/x.yml", "lessons/contrib/a.md"])
    assert groups["other"] == sorted(["scripts/foo.py", ".github/workflows/x.yml"])


def test_the_vocabulary_export_and_the_evidence_table_count_as_generated():
    """Both are produced by the chain, and neither is in the publisher's list.

    `PUBLISHED` answers "what must travel with the site". `data/public-vocabulary.json` and the
    evidence table inside `docs/trust-semantics.md` are generated but not published — a rebuild that
    classified them as `other` would refuse every lesson pull request that touches them, and one that
    ignored them would leave the branch red for a reason nobody can fix by hand.
    """
    assert rebuild.is_generated("data/public-vocabulary.json")
    assert rebuild.is_generated("docs/trust-semantics.md")
    # `docs/data/` is written by `build-feed.yml`, not by this chain: a rebuild leaves `main`'s copy
    # alone, but the file is still not the pull request's change.
    assert rebuild.is_generated("docs/data/feed.json")
    assert not rebuild.is_generated("scripts/rebuild_lesson_pr.py")


def test_the_evidence_table_is_replaced_between_its_marker_and_its_last_line():
    doc = (
        "intro\n\n"
        "<!-- Generated by: python3 scripts/evidence_distribution.py -->\n\n"
        "| Level | Lessons |\n|---|---|\n| **E0** | 1 |\n\n"
        "- Total lessons: **1**\n- At **E4** (observed): **0**\n\n"
        "Three things this says that the definitions above do not:\n"
    )
    fresh = "| Level | Lessons |\n|---|---|\n| **E0** | 2 |\n\n- Total lessons: **2**"
    out = rebuild.patch_evidence_table(doc, fresh)
    assert "| **E0** | 2 |" in out and "| **E0** | 1 |" not in out
    assert "Three things this says" in out, "the hand-written prose after the block must survive"
    assert out.startswith("intro"), "the hand-written prose before the block must survive"


def test_a_document_without_the_marker_is_an_error_rather_than_a_silent_no_op():
    try:
        rebuild.patch_evidence_table("no marker here", "table")
    except ValueError as error:
        assert "not found" in str(error)
    else:
        raise AssertionError("a missing marker must raise — a silent no-op leaves the check red")


def test_the_commit_keeps_the_contributor_and_adds_the_maintainer():
    message = rebuild.commit_message(
        "feat(lessons): promote ten drafts\n\nBody line.\n\n"
        "Signed-off-by: them <them@example.com>\nCo-authored-by: someone <s@e>",
        "them <them@example.com>",
    )
    assert message.startswith("feat(lessons): promote ten drafts")
    assert message.count("Co-authored-by:") == 1, (
        "the original's trailers belong to their commit; repeating them here double-counts")
    assert "Signed-off-by:" not in message, "the caller adds its own with `git commit -s`"
    assert "Body line." in message


def test_an_author_without_an_email_still_gets_a_valid_trailer():
    message = rebuild.commit_message("feat: x", "zsxh1990")
    assert "Co-authored-by: zsxh1990 <zsxh1990@users.noreply.github.com>" in message


def test_the_generator_chain_refuses_to_run_on_windows():
    """Both failure modes were measured on this checkout, not imagined.

    2026-11-15: the same four generators on Windows produced **778** lessons instead of 940 — every
    lesson whose filename is not ASCII vanished with no error. And when the chain did write from
    Windows, 21 tracked files came out CRLF (`102549 insertions(+), 102549 deletions(-)`: same
    content, every line changed), which `tests/test_tracked_text_files_are_lf.py` refuses.
    """
    refusal = rebuild.platform_refusal("nt")
    assert refusal and "POSIX" in refusal
    assert "778" in refusal, "the message must carry the measurement, or the next reader retries it"
    assert rebuild.platform_refusal("posix") is None
