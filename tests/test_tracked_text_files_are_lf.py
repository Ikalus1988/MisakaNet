#!/usr/bin/env python3
"""No tracked text file may be committed with CRLF line endings.

Why this is not redundant with `.gitattributes`
------------------------------------------------
That file says the opposite thing, on purpose: it sets `eol=lf` for `*.sh` **only**, and its comment
explains why a blanket rule was rejected — "CRLF is fatal to `bash`, and harmless to everything else
this repository executes. Python 3's tokenizer accepts it, Node does, and `git diff` normalises on
`text` files anyway."

That reasoning is right about breakage and wrong about `git diff`. The repo has no `text` attribute
on `.py`/`.md`/`.yml` and `core.autocrlf` is `false` here, so git stores bytes exactly as given and
the diff does **not** normalise. Measured 2026-10-13: a 37-line addition to a test file landed as
123 insertions / 87 deletions because every line became CRLF.

So nothing is broken — and that is what makes it expensive. The damage is confined to review: a
reviewer sees a whole-file rewrite, cannot tell the real change from the line-ending change, and
either skims it or reverts it. Four times in one session that shape cost a full investigation
before anyone noticed: `tests/test_issue_quality_gate.py`, `tests/test_domain_vocabulary.py`,
`tests/test_dev_install_path.py`, and — caught only by this test — `scripts/lesson_gate.py` and
`.github/PULL_REQUEST_TEMPLATE.md`, which had been on `main` since an earlier change.

What the repository already looked like
---------------------------------------
Measured over every tracked file of each type on 2026-10-13:

    *.py    568 files   1 with CRLF      *.mjs   89 files   0
    *.md    940 files   1 with CRLF      *.sh    24 files   0
    *.yml   103 files   0                *.json  214 files  0

Two offenders out of 1938, both of them mine, both now fixed. LF is what this repository already
is; this gate says so out loud instead of leaving it to be rediscovered one mangled diff at a time.

Scope
-----
`*.sh` is not re-checked here — `tests/test_shell_scripts_are_lf.py` owns it, and its own docstring
says the rule belongs to `.gitattributes`. This test covers the other text types, because for them
CRLF is not a build failure and therefore nothing else in the suite will ever mention it.

Usage:
    python3 tests/test_tracked_text_files_are_lf.py
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# The text types this repository writes by hand. `data/lessons.json` is generated and deliberately
# not listed — it is 1.26 MB of regenerated bytes, and the generated-artifact gates own it.
TEXT_PATTERNS = ("*.py", "*.md", "*.yml", "*.json", "*.mjs")

CRLF = b"\r\n"


def _tracked_blobs() -> list[tuple[str, bytes]]:
    """Every tracked text file with the bytes that are committed for it.

    Read through `git cat-file --batch` rather than a `git show` per path: this covers ~1900 files
    and spawning one process each took 93 seconds in the first version, which is long enough that a
    suite would grow a habit of skipping it.

    Blobs come from the index, so a path staged but not yet in HEAD is checked too — the question
    is what will be committed, not what is already there.
    """
    listed = subprocess.run(
        ["git", "ls-files", "-s", "--", *TEXT_PATTERNS],
        cwd=REPO, capture_output=True, text=True, check=True,
    ).stdout.splitlines()

    wanted = []
    for line in listed:
        meta, path = line.split("\t", 1)
        wanted.append((meta.split()[1], path))
    if not wanted:
        return []

    proc = subprocess.run(
        ["git", "cat-file", "--batch"],
        cwd=REPO, input=("\n".join(sha for sha, _ in wanted) + "\n").encode(),
        capture_output=True, check=True,
    )
    out = proc.stdout
    blobs: list[tuple[str, bytes]] = []
    pos = 0
    for _, path in wanted:
        nl = out.index(b"\n", pos)             # "<sha> blob <size>\n"
        size = int(out[pos:nl].split()[2])
        start = nl + 1
        blobs.append((path, out[start:start + size]))
        pos = start + size + 1                # + 1 for the trailing newline
    return blobs


def test_no_tracked_text_file_carries_crlf():
    offenders: list[str] = []
    for path, blob in _tracked_blobs():
        if CRLF in blob:
            lines = blob.count(CRLF)
            offenders.append(f"{path} ({lines} CRLF line(s) of {blob.count(chr(10).encode())} lines)")

    assert not offenders, (
        "these tracked text files are committed with CRLF line endings:\n  - "
        + "\n  - ".join(offenders)
        + "\n\nNothing executes wrong — Python's tokenizer accepts CRLF — which is the problem: the "
        "cost lands entirely on review, as a whole-file diff where the real change is invisible. "
        "Convert with:\n    python3 -c \"import pathlib,sys; "
        "[pathlib.Path(p).write_bytes(pathlib.Path(p).read_bytes().replace(b'\\r\\n', b'\\n')) "
        "for p in sys.argv[1:]]\" <files...>\n\n"
        "`.gitattributes` sets `eol=lf` for `*.sh` only, and that is deliberate — it is about bash, "
        "which is the only thing here CRLF actually breaks. This gate is about the other half: the "
        "review that never sees the change."
    )


if __name__ == "__main__":
    try:
        test_no_tracked_text_file_carries_crlf()
    except AssertionError as exc:
        print(f"FAIL test_no_tracked_text_file_carries_crlf\n  {exc}\n")
        sys.exit(1)
    print("ok   test_no_tracked_text_file_carries_crlf")
    print("\npassed: 0 failure(s)")
